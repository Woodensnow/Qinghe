class ApiFixture(unittest.TestCase):
    def setUp(self):
        scratch = Path(__file__).resolve().parents[1] / 'tmp'
        scratch.mkdir(exist_ok=True)
        self.temp = tempfile.TemporaryDirectory(dir=scratch)
        self.old_file, self.old_db, self.old_uploads = store.DATA_FILE, store._db, server.UPLOADS
        store.DATA_FILE = Path(self.temp.name) / 'data.json'
        store._db = store.build_seed()
        store.save()
        server.UPLOADS = Path(self.temp.name) / 'uploads'
        # Ignore any AI polish config on the developer machine; tests set their own.
        self.env = patch.dict(os.environ, {'NO_PROXY': '*', 'no_proxy': '*'})
        self.env.start()
        for key in [k for k in os.environ if k.startswith('QINGHE_POLISH_')]:
            del os.environ[key]
        self.config = patch.object(polish_providers, 'CONFIG_FILE', Path(self.temp.name) / 'ai_polish.local.json')
        self.config.start()
        self.http = server.ThreadingHTTPServer(('127.0.0.1', 0), server.Handler)
        self.thread = threading.Thread(target=self.http.serve_forever, daemon=True)
        self.thread.start()
        self.token = None

    def tearDown(self):
        self.http.shutdown()
        self.http.server_close()
        self.thread.join()
        self.config.stop()
        self.env.stop()
        store.DATA_FILE, store._db, server.UPLOADS = self.old_file, self.old_db, self.old_uploads
        self.temp.cleanup()

    def request(self, method, path, body=None, token=None, raw=False):
        connection = http.client.HTTPConnection(*self.http.server_address, timeout=10)
        headers = {'Content-Type': 'application/json'}
        if token or self.token:
            headers['Authorization'] = 'Bearer ' + (token or self.token)
        connection.request(method, path, body=json.dumps(body) if body is not None else None, headers=headers)
        response = connection.getresponse()
        content = response.read()
        status, response_headers = response.status, dict(response.getheaders())
        connection.close()
        return status, content if raw else json.loads(content), response_headers

    def login(self):
        status, body, _ = self.request('POST', '/api/auth/login', {'email': 'demo@qinghe.cn', 'password': 'qinghe123'})
        self.assertEqual(status, 200)
        self.token = body['token']

    def register(self, email='test@example.cn'):
        status, body, _ = self.request('POST', '/api/auth/register', dict(name='测试旅人', email=email, password='test1234'))
        self.assertEqual(status, 201)
        return body['token']


