    def test_concurrent_messages_are_saved(self):
        self.login()
        endpoint = '/api/conversations/c_demo_lin/messages'
        with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool:
            results = list(pool.map(lambda i: self.request('POST', endpoint, {'body': f'并发消息{i}'}), range(16)))
