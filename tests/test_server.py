        self.assertTrue(result['guide']['isOwner'])
        self.assertEqual(self.request('POST', '/api/conversations', dict(guideId=guide_id))[0], 400)
        traveler = self.register()
        status, result, _ = self.request('POST', '/api/conversations', dict(guideId=guide_id), token=traveler)
        self.assertEqual(status, 201)
        conversation_id = result['conversation']['id']
        endpoint = f'/api/conversations/{conversation_id}/messages'
        self.assertEqual(self.request('POST', endpoint, {'body': '你好'}, token=traveler)[0], 201)
        self.assertEqual(self.request('GET', '/api/messages/unread')[1]['count'], baseline + 1)
        self.assertEqual(self.request('GET', endpoint)[1]['conversation']['role'], 'guide')
        self.assertEqual(self.request('GET', '/api/messages/unread')[1]['count'], baseline)
        self.request('POST', endpoint, {'body': '欢迎来上海'})
        self.assertEqual(self.request('GET', '/api/messages/unread', token=traveler)[1]['count'], 1)
        stranger = self.register('stranger@example.cn')
        self.assertEqual(self.request('GET', endpoint, token=stranger)[0], 404)
        self.assertEqual(self.request('PATCH', f'/api/guides/{guide_id}', {'status': 'paused'})[0], 200)
        self.assertEqual(self.request('GET', f'/api/guides/{guide_id}', token=traveler)[0], 404)
